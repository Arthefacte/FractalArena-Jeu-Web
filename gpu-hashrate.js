  // doit gagner contre « RTX 4070 », et « RTX 4060 Laptop GPU » contre « RTX 4060 ».
  const INDEX = GPU_TABLE
    .filter((e) => e.detect)
    .map((e) => ({ entry: e, d: e.detect.toLowerCase(), len: e.detect.length }));

  function resolveGpu(raw) {
    const nom = normalizeGpuName(raw);
    if (!nom) return { nom: "", gh: null, mesure: false, connu: false };
    const bas = nom.toLowerCase();
    // Le renderer porte souvent la taille mémoire (« RTX 3050 6GB Laptop GPU ») alors que
    // la table ne distingue que quelques modèles par mémoire : on cherche sur les deux
    // formes et on garde la correspondance la plus longue.
    const sansMemoire = bas.replace(/\b\d+\s*(?:GB|MB)\b/gi, " ").replace(/\s+/g, " ").trim();
    let best = null;
    let bestLen = -1;
    for (const item of INDEX) {
      if (item.len > bestLen && (bas.indexOf(item.d) !== -1 || sansMemoire.indexOf(item.d) !== -1)) {
        best = item.entry;
        bestLen = item.len;
      }
    }
    if (best) {
      return { nom: best.nom, gh: best.gh, mesure: best.mesure, connu: true };
    }
    const fb = FALLBACKS.find((f) => f.match.test(nom));
    if (fb) return { nom: fb.nom, gh: fb.gh, mesure: false, connu: true };
    return { nom, gh: null, mesure: false, connu: false };
  }

